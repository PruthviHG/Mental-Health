"""Builds assets/css/icons.css: the 14 Font Awesome icons Mindsence uses, as tiny inline SVG masks.

It replaces the whole Font Awesome download (a 127 KB font + 60 KB stylesheet) with about 6 KB, and the existing
`fas fa-name` class names keep working. Icons come from Font Awesome Free (CC BY 4.0, https://fontawesome.com/license/free).

Run:  python tools/build_icons.py  <path to node_modules/@fortawesome/fontawesome-free/svgs/solid>
"""
import os
import re
import sys
import urllib.parse

# class name -> svg file in Font Awesome's "solid" set
ICONS = {
    "times": "xmark", "image": "image", "microphone": "microphone", "play": "play", "pause": "pause", "volume-low": "volume-low",
    "step-forward": "forward-step", "forward": "forward", "backward": "backward", "satellite-dish": "satellite-dish",
    "paper-plane": "paper-plane", "music": "music", "envelope": "envelope", "comment-dots": "comment-dots", "arrow-left": "arrow-left",
}


def main(src):
    out = [
        "/* Generated by tools/build_icons.py - Font Awesome Free icons (CC BY 4.0), used as masks so they follow the text colour. */",
        ".fas{display:inline-block;width:1em;height:1em;vertical-align:-.125em;background-color:currentColor;"
        "-webkit-mask:var(--i) center/contain no-repeat;mask:var(--i) center/contain no-repeat}",
    ]
    for cls, name in ICONS.items():
        svg = open(os.path.join(src, name + ".svg"), encoding="utf-8").read()
        svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S).strip()
        svg = re.sub(r"\s+", " ", svg)
        out.append('.fa-%s{--i:url("data:image/svg+xml,%s")}' % (cls, urllib.parse.quote(svg, safe="/:=,' ()")))
    css = "\n".join(out) + "\n"
    dest = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "assets", "css", "icons.css")
    with open(dest, "w", encoding="utf-8") as f:
        f.write(css)
    print("wrote", dest, len(css), "bytes")


if __name__ == "__main__":
    main(sys.argv[1])
